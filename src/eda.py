"""Exploratory data analysis and reporting for the retail sales dataset.

Produces summary tables and all figures under reports/figures/ and a
Markdown report under reports/.
"""
from pathlib import Path

import matplotlib.pyplot as plt
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
DATA_PATH = ROOT / "data" / "processed" / "retail_sales_clean.csv"
FIG_DIR = ROOT / "reports" / "figures"
REPORT_PATH = ROOT / "reports" / "analysis_report.md"

plt.rcParams.update({
    "figure.dpi": 120,
    "axes.spines.top": False,
    "axes.spines.right": False,
    "axes.titleweight": "bold",
})

COLOR = "#4C72B0"


def load_data() -> pd.DataFrame:
    return pd.read_csv(DATA_PATH, parse_dates=["order_date"])


def fig_monthly_trend(df: pd.DataFrame) -> None:
    monthly = df.set_index("order_date")["net_revenue"].resample("ME").sum()
    ax = monthly.plot(figsize=(10, 4), color=COLOR, lw=2)
    monthly.rolling(3).mean().plot(ax=ax, color="#DD8452", lw=2,
                                   ls="--", label="3-month avg")
    ax.set_title("Monthly Net Revenue (2023-2025)")
    ax.set_xlabel("")
    ax.set_ylabel("Net Revenue ($)")
    ax.legend()
    plt.tight_layout()
    plt.savefig(FIG_DIR / "monthly_revenue_trend.png")
    plt.close()


def fig_category_revenue(df: pd.DataFrame) -> None:
    cat = df.groupby("category")["net_revenue"].sum().sort_values()
    ax = cat.plot(kind="barh", figsize=(8, 4), color=COLOR)
    ax.set_title("Total Net Revenue by Category")
    ax.set_xlabel("Net Revenue ($)")
    ax.set_ylabel("")
    plt.tight_layout()
    plt.savefig(FIG_DIR / "revenue_by_category.png")
    plt.close()


def fig_region_channel(df: pd.DataFrame) -> None:
    pivot = df.pivot_table(values="net_revenue", index="region",
                           columns="channel", aggfunc="sum")
    ax = pivot.plot(kind="bar", figsize=(8, 4), rot=0)
    ax.set_title("Net Revenue by Region and Channel")
    ax.set_xlabel("")
    ax.set_ylabel("Net Revenue ($)")
    ax.legend(title="Channel")
    plt.tight_layout()
    plt.savefig(FIG_DIR / "revenue_by_region_channel.png")
    plt.close()


def fig_return_rate(df: pd.DataFrame) -> None:
    ret = df.groupby("category")["returned"].mean().mul(100).sort_values(ascending=False)
    ax = ret.plot(kind="bar", figsize=(8, 4), rot=30, color="#C44E52")
    ax.set_title("Return Rate by Category (%)")
    ax.set_xlabel("")
    ax.set_ylabel("Return Rate (%)")
    ax.axhline(ret.mean(), color="grey", ls="--", lw=1, label="Overall avg")
    ax.legend()
    plt.tight_layout()
    plt.savefig(FIG_DIR / "return_rate_by_category.png")
    plt.close()


def fig_discount_impact(df: pd.DataFrame) -> None:
    eff = df.groupby("discount_pct")["net_revenue"].mean()
    ax = eff.plot(kind="bar", figsize=(7, 4), rot=0, color="#55A868")
    ax.set_title("Average Net Revenue by Discount Level")
    ax.set_xlabel("Discount (%)")
    ax.set_ylabel("Avg Net Revenue / Order ($)")
    plt.tight_layout()
    plt.savefig(FIG_DIR / "discount_impact.png")
    plt.close()


def build_summary_tables(df: pd.DataFrame) -> dict[str, pd.DataFrame]:
    kpis = pd.DataFrame({
        "metric": ["Total net revenue", "Orders", "Avg order value",
                   "Return rate (%)", "Unique customers"],
        "value": [
            f"${df['net_revenue'].sum():,.0f}",
            f"{len(df):,}",
            f"${df['net_revenue'].mean():,.2f}",
            f"{df['returned'].mean() * 100:.1f}%",
            f"{df['customer_id'].nunique():,}",
        ],
    })
    category_summary = df.groupby("category").agg(
        orders=("order_id", "count"),
        net_revenue=("net_revenue", "sum"),
        avg_order_value=("net_revenue", "mean"),
        return_rate=("returned", "mean"),
    ).round(2).sort_values("net_revenue", ascending=False)
    monthly_growth = (
        df.set_index("order_date")["net_revenue"]
        .resample("ME").sum().pct_change().dropna()
        .describe().round(4).to_frame("monthly_growth")
    )
    return {"kpis": kpis, "category_summary": category_summary,
            "monthly_growth": monthly_growth}


def write_report(df: pd.DataFrame, tables: dict[str, pd.DataFrame]) -> None:
    kpis = tables["kpis"]
    cat = tables["category_summary"]
    growth = tables["monthly_growth"]
    lines = [
        "# Retail Sales Analysis - Report",
        "",
        "Automated report generated by `src/eda.py`.",
        "",
        "## Key Performance Indicators",
        "",
        kpis.to_markdown(index=False),
        "",
        "## Category Performance",
        "",
        cat.to_markdown(),
        "",
        f"- **Best category by revenue:** {cat['net_revenue'].idxmax()}",
        f"- **Highest return rate:** {cat['return_rate'].idxmax()} "
        f"({cat['return_rate'].max() * 100:.1f}%)",
        f"- **Avg monthly revenue growth:** {growth.loc['mean', 'monthly_growth'] * 100:.2f}% "
        f"(std {growth.loc['std', 'monthly_growth'] * 100:.2f}%)",
        "",
        "## Figures",
        "",
        "![Monthly revenue trend](figures/monthly_revenue_trend.png)",
        "",
        "![Revenue by category](figures/revenue_by_category.png)",
        "",
        "![Revenue by region and channel](figures/revenue_by_region_channel.png)",
        "",
        "![Return rate by category](figures/return_rate_by_category.png)",
        "",
        "![Discount impact](figures/discount_impact.png)",
        "",
        "More charts: run `python src/visuals.py` (see `reports/figures/`).",
    ]
    REPORT_PATH.write_text(chr(10).join(lines))
    print(f"Saved -> {REPORT_PATH}")


def main() -> None:
    FIG_DIR.mkdir(parents=True, exist_ok=True)
    df = load_data()
    print(f"Loaded {len(df):,} rows")

    fig_monthly_trend(df)
    fig_category_revenue(df)
    fig_region_channel(df)
    fig_return_rate(df)
    fig_discount_impact(df)
    print(f"Figures saved -> {FIG_DIR}")

    tables = build_summary_tables(df)
    write_report(df, tables)

    print()
    print("=== KPIs ===")
    print(tables["kpis"].to_string(index=False))
    print()
    print("=== Category summary ===")
    print(tables["category_summary"].to_string())


if __name__ == "__main__":
    main()
